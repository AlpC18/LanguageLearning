let current = 'tr';

export function setLocale(locale) {
  current = STRINGS[locale] ? locale : 'tr';
  if (typeof document !== 'undefined') document.documentElement.lang = current;
}

export const locale = () => current;

export function t(key, vars = {}) {
  const text = STRINGS[current][key] ?? STRINGS.tr[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}

export const hasKey = (loc, key) => key in STRINGS[loc];
export const keys = (loc) => Object.keys(STRINGS[loc]);

// Unit text in the current locale, falling back to Turkish while a translation is missing.
export const unitTitle = (unit) => (current === 'en' && unit.titleEn) || unit.title;
// The meaning in the language that is NOT selected, shown as a quiet secondary hint.
export const otherMeaning = ({ tr, en }) => (current === 'en' ? tr : en) ?? '';

export const unitTip = (unit) => (current === 'en' && unit.tipEn) || unit.tip;
